def general_gradient():
    """The fallback rule and its validation, read from data/ so it cannot drift."""
    p = DATA / "general_gradient.csv"
    if not p.exists():
        return None
    g = pd.read_csv(p)
    d = {f"{r['component']}.{r['key']}": r["value"] for _, r in g.iterrows()}
    d["_ages"] = [(r["key"], r["value"]) for _, r in
                  g[g["component"] == "age_offset"].iterrows()]
    return d


def rule_predict(gg, income):
    """The general gradient at an income (GDP per capita, PPP), with its 95% prediction interval."""
    a, b = gg["income_rule.intercept"], gg["income_rule.slope_ln_income"]
    x0 = np.log(income)
    half = (gg["income_rule.t_95"] * gg["income_rule.residual_sd"]
            * np.sqrt(1 + 1 / gg["income_rule.n_observations"]
                      + (x0 - gg["income_rule.mean_ln_income"]) ** 2 / gg["income_rule.sxx_ln_income"]))
    f = a + b * x0
    return f, f - half, f + half


def pi_text(gg, income):
    f, lo, hi = rule_predict(gg, income)
    return f"{fmt(f)} (95% prediction interval {fmt(lo)} to {fmt(hi)})"


def imr_vs_u5mr(lib):
    """How much steeper the U5MR proxy is than the infant series it stands in for."""
    p = lib.pivot_table(index=["country", "year", "source"], columns="indicator",
                        values="slope")
    if "IMR" not in p.columns:
        return None
    p = p[["IMR", "U5MR"]].dropna()
    if not len(p):
        return None
    d = p["IMR"] - p["U5MR"]
    return {"n": len(p), "med_imr": p["IMR"].median(), "med_u5": p["U5MR"].median(),
            "med_diff": d.median(), "share_flatter": (d > 0).mean(),
            "r": p["IMR"].corr(p["U5MR"]),
            "worst": d.abs().idxmax(), "worst_gap": d.abs().max()}


