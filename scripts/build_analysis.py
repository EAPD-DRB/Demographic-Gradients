def asfr_sum_check():
    """5 x the sum of age rates against DHS's TFR, per survey and quintile."""
    raw = pd.read_csv(DATA / "dhs_gradients_raw.csv")
    raw = raw[raw["quintile"].isin(["Lowest", "Second", "Middle", "Fourth", "Highest"])]
    w = raw.pivot_table(index=["survey", "quintile"], columns="indicator",
                        values="value", aggfunc="first")
    a = [c for c in w.columns if c.startswith("ASFR")]
    w = w.dropna(subset=["TFR"] + a)
    gap = (5 * w[a].sum(axis=1) / 1000 - w["TFR"]).abs()
    return {"cells": len(w), "max": gap.max()}


def age_ratios():
    """Median low/high ratio of each age-specific rate, over the surveys behind the offsets.

    Latest survey per country, and only where the age gradient can be estimated
    (every quintile positive), so the ratio and the offset rest on the same surveys.
    """
    t = pd.read_csv(DATA / "fertility_age_tilts.csv").sort_values(["country", "year", "survey"])
    t = t[t["survey"].isin(t.groupby("country")["survey"].last()) & t["slope"].notna()]
    return (t["q1"] / t["q5"]).groupby(t["age_lo"]).median()


