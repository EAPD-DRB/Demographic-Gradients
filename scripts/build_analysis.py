def deaths_15_60(g):
    """Deaths behind a census's 15-60 estimate: both sexes, summed if only by sex."""
    q = g[g["measure"] == "45q15"]
    a = q[q["sex"] == "all"]
    return int(a["n_deaths"].sum() if len(a) else q[q["sex"].isin(["male", "female"])]["n_deaths"].sum())


