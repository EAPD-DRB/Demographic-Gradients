def basis(source):
    """The kind of source of an adult-mortality row: a DHS survey, Bangladesh's
    BMMS (both from build_adult_mortality_survey.py), or a census."""
    s = str(source)
    if s.startswith("The DHS Program"):
        return "DHS survey"
    if "Maternal Mortality and Health Care Survey" in s:
        return "BMMS survey"
    return "census"


def within_country(amr):
    """Countries with two or more 45q15 estimates: (country, [(year, gradient)], [gni])."""
    pts_p = DATA / "general_gradient_points.csv"
    gni = (pd.read_csv(pts_p).set_index(["country", "year"])["gdp_ppp"].to_dict()
           if pts_p.exists() else {})
    q = amr[(amr["measure"] == "45q15") & (amr["sex"] == "all")]
    out = []
    for c, g in q.groupby("country"):
        if g["year"].nunique() > 1:
            g = g.sort_values("year")
            out.append((c, [(int(y), float(v)) for y, v in zip(g["year"], g["slope"])],
                        [gni.get((c, int(y)), np.nan) for y in g["year"]]))
    return out


def amr_headline():
    """One 45q15 observation per census or survey: the 'all' row, else the sex mean."""
    p = DATA / "adult_mortality_gradients.csv"
    if not p.exists():
        return None
    q = pd.read_csv(p)
    q = q[q["measure"] == "45q15"]
    if not len(q):
        return None
    obs, ratios = [], []
    for _, g in q.groupby(["country", "year"]):
        a = g[g["sex"] == "all"]
        src = a if len(a) else g[g["sex"].isin(["male", "female"])]
        obs.append(float(src["slope"].mean()))
        ratios.append(float(src["ratio"].mean()))
    s, r = pd.Series(obs), pd.Series(ratios)
    return {"n": q["country"].nunique(), "observations": len(obs), "med": s.median(),
            "q25": s.quantile(0.25), "q75": s.quantile(0.75), "ratio": r.median()}


def region_table(latest, ind):
    l = latest[latest["indicator"] == ind]
    g = (
        l.groupby("region")
        .agg(
            n=("country", "nunique"),
            med=("slope", "median"),
            q25=("slope", lambda s: s.quantile(0.25)),
            q75=("slope", lambda s: s.quantile(0.75)),
            ratio=("ratio", "median"),
        )
        .sort_values("med")
    )
    rows = []
    for rgn, r in g.iterrows():
        iqr = REGION_ORDER_NOTE if r["n"] == 1 else f"{fmt(r['q25'])} to {fmt(r['q75'])}"
        rows.append(
            f"| {rgn} | {int(r['n'])} | {fmt(r['med'])} | {iqr} | {r['ratio']:.2f} |"
        )
    return "\n".join(rows)


def line_fit_table(latest):
    """How well a straight line in log rate fits the quintiles (latest surveys)."""
    x = np.array(MID_Q)
    rows = []
    for ind, name in (("TFR", "Total fertility rate"), ("IMR", "Infant mortality rate")):
        y = np.log(latest.loc[latest["indicator"] == ind, ["q1", "q2", "q3", "q4", "q5"]]
                   .to_numpy(dtype=float))
        res, r2, bend = [], [], []
        for v in y:
            e = v - np.polyval(np.polyfit(x, v, 1), x)
            res.append(e)
            r2.append(1 - e.var() / v.var())
            bend.append(np.polyfit(x, v, 2)[0] < 0)
        med = np.median(np.array(res), axis=0)
        rows.append(f"| {name} | {len(y)} | "
                    + " | ".join(f"{100 * (np.exp(m) - 1):+.1f}".replace("-", NEG) for m in med)
                    + f" | {np.median(r2):.2f} | {np.mean(bend):.0%} |")
    return ("| Indicator | Countries | Lowest | Second | Middle | Fourth | Highest "
            "| Median R² | Falls faster toward the top |\n|---|---|---|---|---|---|---|---|---|\n"
            + "\n".join(rows) + "\n\n"
            "Quintile columns: median across countries of the difference between the "
            "published rate and the fitted line, in percent of the fitted value. R²: "
            "share of the variation in the five log rates that the line accounts for. "
            "Last column: share of countries whose quintile rates bend downward toward "
            "the richest quintile (negative quadratic term).")


def replace_between(text, start, end, new):
    a, b = text.index(start) + len(start), text.index(end)
    return text[:a] + "\n" + new + "\n" + text[b:]


